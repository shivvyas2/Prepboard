// Writes web/config.js from SUPABASE_URL and SUPABASE_ANON_KEY so the keys never live in git.
// Vercel runs this as the build command; locally, copy web/config.example.js to web/config.js instead.
import { writeFileSync } from "node:fs";

const url = process.env.SUPABASE_URL ?? "";
const anonKey = process.env.SUPABASE_ANON_KEY ?? "";

if (process.env.VERCEL && (!url || !anonKey)) {
  console.error("SUPABASE_URL and SUPABASE_ANON_KEY must be set in the Vercel project settings.");
  process.exit(1);
}

writeFileSync(
  new URL("../web/config.js", import.meta.url),
  `// Generated by scripts/write-web-config.mjs at build time. Do not edit or commit.
// The anon key is public by design; Row Level Security protects the data.
window.PREPBOARD_CONFIG = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(anonKey)},
};
`,
);
console.log(`web/config.js written (${url ? "cloud" : "local-only"} mode)`);
