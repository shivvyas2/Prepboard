-- Prepboard learning: YouTube videos per session, quiz attempts (for the leaderboard / weak topics).

alter table public.pb_sessions
  add column if not exists videos jsonb not null default '[]';   -- [{ "id": "<youtube id>", "title": "", "channel": "", "why": "" }]

create table if not exists public.pb_quiz_attempts (
  user_id      uuid not null default auth.uid() references auth.users (id) on delete cascade,
  id           text not null,
  role_id      text not null default '',
  session_id   text not null default '',
  topic        text not null default '',
  score        int  not null default 0,
  total        int  not null default 0 check (total >= 0 and score between 0 and total),
  items        jsonb not null default '[]',   -- [{ question, options[], answer, chosen, explanation, topic }]
  weak_topics  text[] not null default '{}',
  source       text not null default 'cloud', -- 'claude-code' when generated by the user's own Claude Code
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  primary key (user_id, id)
);

create index if not exists pb_quiz_attempts_user_created on public.pb_quiz_attempts (user_id, created_at desc);

alter table public.pb_quiz_attempts enable row level security;
drop policy if exists "owner select" on public.pb_quiz_attempts;
drop policy if exists "owner insert" on public.pb_quiz_attempts;
drop policy if exists "owner update" on public.pb_quiz_attempts;
drop policy if exists "owner delete" on public.pb_quiz_attempts;
create policy "owner select" on public.pb_quiz_attempts for select to authenticated using ((select auth.uid()) = user_id);
create policy "owner insert" on public.pb_quiz_attempts for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "owner update" on public.pb_quiz_attempts for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "owner delete" on public.pb_quiz_attempts for delete to authenticated using ((select auth.uid()) = user_id);
